"""Rounds: each round has its own RSA-2048 token-signing key.

A fresh key per round means tokens from closed rounds can simply be
rejected, and a token can only ever be used in the round it was issued for.
"""

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

from whisperchain.common import constants as C
from whisperchain.common.encoding import b64_to_int, int_to_b64
from whisperchain.common.files import write_private_file
from whisperchain.server.config import ServerPaths


def get_open_round(conn):
    """The open round row (round, token_n, token_e), or None."""
    return conn.execute(
        "SELECT round, token_n, token_e FROM rounds WHERE status = 'open'"
    ).fetchone()


def get_round(conn, round_number: int):
    return conn.execute(
        "SELECT round, status, token_n, token_e FROM rounds WHERE round = ?", (round_number,)
    ).fetchone()


def public_numbers(row) -> tuple[int, int]:
    return b64_to_int(row["token_n"]), b64_to_int(row["token_e"])


def start_new_round(conn, paths: ServerPaths, private_key: rsa.RSAPrivateKey) -> int:
    """Close the open round and open the next one. Caller owns the transaction.

    The key is generated by the caller BEFORE the transaction, because key
    generation is slow and we do not want to hold the database write lock.
    """
    conn.execute("UPDATE rounds SET status = 'closed' WHERE status = 'open'")
    last = conn.execute("SELECT MAX(round) FROM rounds").fetchone()[0]
    if last is None:
        round_number = 1  # no rounds yet (MAX of an empty table is NULL)
    else:
        round_number = last + 1

    # The private key lives in a 0600 file, never in the database.
    # overwrite=True: if an earlier attempt wrote this file and then rolled
    # back, the leftover file is simply replaced.
    paths.keys_dir.mkdir(exist_ok=True)
    pem = private_key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    )
    write_private_file(paths.round_key(round_number), pem, overwrite=True)

    numbers = private_key.public_key().public_numbers()
    conn.execute(
        "INSERT INTO rounds (round, status, token_n, token_e) VALUES (?, 'open', ?, ?)",
        (round_number, int_to_b64(numbers.n), int_to_b64(numbers.e)),
    )
    return round_number


def generate_round_key() -> rsa.RSAPrivateKey:
    return rsa.generate_private_key(public_exponent=C.RSA_PUBLIC_EXPONENT, key_size=C.ROUND_KEY_BITS)


def load_round_private_key(paths: ServerPaths, round_number: int) -> rsa.RSAPrivateKey:
    return serialization.load_pem_private_key(paths.round_key(round_number).read_bytes(), password=None)
